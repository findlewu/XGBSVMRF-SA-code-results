# -*- coding: utf-8 -*-
"""One common no-resampling, pot-grouped five-fold comparison.

All methods use the same outer folds (seed 20260929). Stacking probabilities
are generated by three-fold pot-grouped OOF prediction inside each outer
training partition. Spectral-angle centres and the meta learner are fitted
from training data only. XGBoost uses CUDA; no class resampling, class weights,
or grade-0/1 threshold are used.
"""
from __future__ import annotations

import gc
import json
import time
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import accuracy_score, classification_report, f1_score
from sklearn.model_selection import StratifiedGroupKFold
import xgboost

import run_repeated_grouped_sa_ablation as base
import run_fixed_sa_no_resampling_gpu as final


SEED = 20260929
OUT = base.ROOT / "work" / "final_common_grouped_fivefold_gpu"
OUT.mkdir(parents=True, exist_ok=True)

REGION_COLUMNS = {
    "VIS": np.arange(0, 6),
    "Red-edge": np.arange(6, 12),
    "NIR": np.arange(12, 18),
    "SWIR": np.arange(18, 24),
    "NIR+SWIR": np.arange(12, 24),
    "All-region": np.arange(24),
}


def stack_predict(oof_blocks, test_blocks, sa_oof, sa_test, y_train, seed):
    base_train = np.hstack(oof_blocks)
    base_test = np.hstack(test_blocks)
    return final.meta_predict_same_settings(
        np.hstack([base_train, sa_oof]),
        y_train,
        np.hstack([base_test, sa_test]),
        seed,
    )


def evaluate_fold(X, y, groups, meta, wave, fold, train_idx, test_idx):
    X_train, X_test = X[train_idx], X[test_idx]
    y_train, y_test = y[train_idx], y[test_idx]
    groups_train = groups[train_idx]
    model_seed = SEED + fold * 1000

    oof, test, sa_oof, sa_test = (
        final.inner_oof_and_outer_predictions_no_resampling(
            X_train, y_train, groups_train, X_test, wave, model_seed
        )
    )

    predictions = {
        "SVM": test["svm"].argmax(axis=1),
        "RF": test["rf"].argmax(axis=1),
        "XGBoost": test["xgb"].argmax(axis=1),
        "XGB-SVM": stack_predict(
            [oof["xgb"], oof["svm"]],
            [test["xgb"], test["svm"]],
            np.empty((len(y_train), 0)),
            np.empty((len(y_test), 0)),
            y_train,
            model_seed,
        ),
        "XGB-SVM-RF": stack_predict(
            [oof["xgb"], oof["svm"], oof["rf"]],
            [test["xgb"], test["svm"], test["rf"]],
            np.empty((len(y_train), 0)),
            np.empty((len(y_test), 0)),
            y_train,
            model_seed,
        ),
    }

    base_oof = [oof["xgb"], oof["svm"], oof["rf"]]
    base_test = [test["xgb"], test["svm"], test["rf"]]
    for region_name, columns in REGION_COLUMNS.items():
        predictions[f"XGBSVMRF-SA ({region_name})"] = stack_predict(
            base_oof,
            base_test,
            sa_oof[:, columns],
            sa_test[:, columns],
            y_train,
            model_seed,
        )

    metrics = []
    prediction_rows = []
    for model_name, prediction in predictions.items():
        metrics.append(
            {
                "fold": fold,
                "model": model_name,
                "accuracy": accuracy_score(y_test, prediction),
                "macro_f1": f1_score(y_test, prediction, average="macro"),
                "n_test_spectra": len(test_idx),
                "n_test_pots": len(np.unique(groups[test_idx])),
            }
        )
        for local_index, predicted_grade in enumerate(prediction):
            row_index = int(test_idx[local_index])
            prediction_rows.append(
                {
                    "fold": fold,
                    "model": model_name,
                    "row_index": row_index,
                    "true_grade": int(y_test[local_index]),
                    "predicted_grade": int(predicted_grade),
                    "pot_id": str(groups[row_index]),
                    "source_file": str(meta.iloc[row_index]["source_file"]),
                    "date": str(meta.iloc[row_index]["Date"]),
                }
            )
    return pd.DataFrame(metrics), pd.DataFrame(prediction_rows)


def summarise(metrics, predictions):
    summary = (
        metrics.groupby("model", as_index=False)
        .agg(
            accuracy_mean=("accuracy", "mean"),
            accuracy_sd=("accuracy", "std"),
            macro_f1_mean=("macro_f1", "mean"),
            macro_f1_sd=("macro_f1", "std"),
        )
        .sort_values(["macro_f1_mean", "accuracy_mean"], ascending=False)
    )
    summary.to_csv(OUT / "model_summary_mean_sd.csv", index=False)

    class_rows = []
    for model_name, group in predictions.groupby("model"):
        report = classification_report(
            group["true_grade"],
            group["predicted_grade"],
            labels=range(6),
            output_dict=True,
            zero_division=0,
        )
        for grade in range(6):
            class_rows.append(
                {
                    "model": model_name,
                    "grade": grade,
                    "precision": report[str(grade)]["precision"],
                    "recall": report[str(grade)]["recall"],
                    "f1": report[str(grade)]["f1-score"],
                    "support": report[str(grade)]["support"],
                }
            )
    pd.DataFrame(class_rows).to_csv(OUT / "pooled_per_class_metrics.csv", index=False)

    metadata = {
        "dataset": "833 spectra from 40 complete pots; grades 0-5",
        "outer_validation": "one five-fold StratifiedGroupKFold by pot",
        "outer_seed": SEED,
        "inner_stacking": "three-fold StratifiedGroupKFold by pot",
        "preprocessing": "Savitzky-Golay smoothing followed by second derivative",
        "resampling": "none",
        "class_weight": None,
        "grade01_threshold": None,
        "meta_learner": "standardized logistic regression, C=0.3",
        "SA_centres": "group-balanced grade centres fitted within each training partition",
        "xgboost_device": "cuda",
        "xgboost_version": xgboost.__version__,
        "xgboost_cuda_build": bool(xgboost.build_info().get("USE_CUDA")),
        "note": "Mean and SD describe variation across five pot-grouped folds, not independent external cohorts.",
    }
    (OUT / "run_metadata.json").write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2), encoding="utf-8"
    )


def main():
    start = time.time()
    raw, meta_all, wave, files = base.load_data()
    pots = base.complete_pots(meta_all)
    mask = meta_all["pot_id"].astype(str).isin(pots).to_numpy()
    X = base.preprocess(raw)[mask]
    meta = meta_all.loc[mask].reset_index(drop=True)
    y = meta["stage"].to_numpy(dtype=int)
    groups = meta["pot_id"].astype(str).to_numpy()
    print(
        f"Dataset: {len(y)} spectra, {len(np.unique(groups))} pots, "
        f"grades={np.bincount(y).tolist()}, source_files={len(files)}"
    )

    metrics_frames = []
    prediction_frames = []
    outer = StratifiedGroupKFold(n_splits=5, shuffle=True, random_state=SEED)
    for fold, (train_idx, test_idx) in enumerate(
        outer.split(X, y, groups), start=1
    ):
        metrics_path = OUT / f"checkpoint_fold_{fold}_metrics.csv"
        predictions_path = OUT / f"checkpoint_fold_{fold}_predictions.csv"
        if metrics_path.exists() and predictions_path.exists():
            fold_metrics = pd.read_csv(metrics_path)
            fold_predictions = pd.read_csv(predictions_path, dtype={"pot_id": str})
            print(f"fold {fold}/5: loaded checkpoint")
        else:
            tic = time.time()
            fold_metrics, fold_predictions = evaluate_fold(
                X, y, groups, meta, wave, fold, train_idx, test_idx
            )
            fold_metrics.to_csv(metrics_path, index=False)
            fold_predictions.to_csv(predictions_path, index=False)
            chosen = fold_metrics[
                fold_metrics["model"].eq("XGBSVMRF-SA (NIR+SWIR)")
            ].iloc[0]
            print(
                f"fold {fold}/5: {time.time()-tic:.1f}s; "
                f"accuracy={chosen['accuracy']:.4f}, macro_f1={chosen['macro_f1']:.4f}"
            )
        metrics_frames.append(fold_metrics)
        prediction_frames.append(fold_predictions)
        gc.collect()

    metrics = pd.concat(metrics_frames, ignore_index=True)
    predictions = pd.concat(prediction_frames, ignore_index=True)
    metrics.to_csv(OUT / "all_fold_metrics.csv", index=False)
    predictions.to_csv(OUT / "all_out_of_fold_predictions.csv", index=False)
    summarise(metrics, predictions)
    print(f"Completed in {(time.time()-start)/60:.1f} min. Outputs: {OUT}")


if __name__ == "__main__":
    main()
